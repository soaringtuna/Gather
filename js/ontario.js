export function gradeNumber(gradeLabel, code) {
  const match = String(gradeLabel || "").match(/Grade\s+(\d+)/);
  if (match) {
    const grade = Number(match[1]);
    if (grade >= 9 && grade <= 12) return grade;
  }
  const digit = String(code || "")[3];
  if (digit === "1") return 9;
  if (digit === "2") return 10;
  if (digit === "3") return 11;
  if (digit === "4") return 12;
  return 10;
}

export function findOntarioCourse(code) {
  const key = String(code || "").trim().toUpperCase();
  const row = BY_CODE.get(key);
  if (!row) return null;
  return { code: row[0], title: row[1], gradeLabel: row[2], grade: gradeNumber(row[2], row[0]) };
}

export function searchOntarioCourses(query, limit = 40) {
  const needle = String(query || "").trim().toLowerCase();
  if (!needle) return [];
  const hits = [];
  for (const row of ONTARIO_COURSES) {
    if (row[0].toLowerCase().includes(needle) || row[1].toLowerCase().includes(needle)) {
      hits.push({ code: row[0], title: row[1], gradeLabel: row[2], grade: gradeNumber(row[2], row[0]) });
      if (hits.length >= limit) break;
    }
  }
  return hits;
}

export function expectationsForCode(code, options = {}) {
  const includeSpecific = options.includeSpecific === true;
  const course = findOntarioCourse(code);
  const doc = BY_COURSE[String(code || "").trim().toUpperCase()];
  if (!course || !doc) return { citation: "", items: [], hasSpecific: false };
  const specifics = doc.items.filter((item) => item.group);
  const overalls = doc.items.filter((item) => !item.group);
  const chosen = [];
  const present = (item, group) => ({
    id: `${doc.id}-${item.code.replace(/\s+/g, "-").toLowerCase()}`,
    label: `${item.code} ${item.title}`,
    group,
    detail: item.group
      ? `Specific expectation ${item.code}, under ${item.group}.`
      : `Overall expectation ${item.code}: ${item.title}.`,
  });
  if (overalls.length) {
    const attached = new Set();
    for (const overall of overalls) {
      const family = `${overall.code} ${overall.title}`;
      chosen.push(present(overall, includeSpecific ? family : ""));
      if (!includeSpecific) continue;
      for (const item of specifics) {
        if (attached.has(item) || item.group !== family) continue;
        attached.add(item);
        chosen.push(present(item, item.group));
      }
    }
    if (includeSpecific) {
      for (const item of specifics) {
        if (attached.has(item)) continue;
        chosen.push(present(item, item.group));
      }
    }
  } else if (!includeSpecific) {
    const seen = new Set();
    for (const item of specifics) {
      const codePart = item.group.split(" ")[0];
      if (!codePart || seen.has(codePart)) continue;
      seen.add(codePart);
      chosen.push(present({ code: codePart, title: item.group.slice(codePart.length).trim(), group: "" }, ""));
    }
  } else {
    chosen.push(...specifics.map((item) => present(item, item.group)));
  }
  return { citation: doc.citation, hasSpecific: specifics.length > 0, items: chosen };
}
